import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

/**
 * One SVG supplies both renderers, browser icons and the native launcher artwork. Kept beside
 * the desktop image tooling so regeneration uses its existing sharp dependency.
 * `pnpm brand:generate` writes the assets; `pnpm brand:check` checks committed output for drift.
 */
const repo = fileURLToPath(new URL("../../../", import.meta.url));
const check = process.argv.includes("--check");
const source = await readFile(resolve(repo, "assets/brand/rowcat-symbol.svg"), "utf8");
const viewBox = /viewBox="([^"]+)"/.exec(source)?.[1];
const path = /<path d="([^"]+)"/.exec(source)?.[1];
if (!viewBox || !path || source.match(/<path\b/g)?.length !== 1)
	throw new Error("The brand SVG must have a viewBox and a single path.");

// Artwork colour, independent of UI themes. Must match Android's adaptiveIcon.backgroundColor.
const background = "#644ebd";
const outputs = new Map<string, Buffer>();
const svg = (colour: string, size: number, inset = 0) =>
	Buffer.from(
		`<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}"><svg x="${inset}" y="${inset}" width="${size - 2 * inset}" height="${size - 2 * inset}" viewBox="${viewBox}" fill="${colour}"><path d="${path}"/></svg></svg>`,
	);
const png = async (size: number, inset: number) =>
	sharp({ create: { width: size, height: size, channels: 3, background } })
		.composite([{ input: svg("#ffffff", size, inset) }])
		.removeAlpha()
		.png()
		.toBuffer();

outputs.set(
	"packages/design/src/brand.ts",
	Buffer.from(
		`// Generated by pnpm brand:generate from assets/brand/rowcat-symbol.svg. Do not edit.\nexport const BRAND_SYMBOL_VIEW_BOX = "${viewBox}";\nexport const BRAND_SYMBOL_PATH =\n\t"${path}";\n`,
	),
);

// The favicon follows the browser's theme independently of the app's settings.
const favicon = Buffer.from(
	`<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}"><style>path{fill:#171717}@media(prefers-color-scheme:dark){path{fill:#fff}}</style><path d="${path}"/></svg>\n`,
);
for (const app of ["web", "admin"]) {
	outputs.set(`apps/${app}/public/favicon.svg`, favicon);
	outputs.set(`apps/${app}/public/apple-touch-icon.png`, await png(180, 28));
}

// iOS gets an opaque tile with system-rounded corners. Desktop derives its icons from this tile.
outputs.set("apps/mobile/assets/icon.png", await png(1024, 144));
// The whole foreground square fits inside Android's 66/108 circular parallax-safe zone:
// 432 * sqrt(2) < 1024 * 66/108. Extra transparent space also makes launcher masks safe.
outputs.set(
	"apps/mobile/assets/adaptive-icon.png",
	await sharp(svg("#ffffff", 1024, 296)).png().toBuffer(),
);

const stale: string[] = [];
for (const [name, bytes] of outputs) {
	const destination = resolve(repo, name);
	if (check) {
		const current = await readFile(destination).catch(() => null);
		const normalized =
			current && /\.(ts|svg)$/.test(name)
				? Buffer.from(current.toString("utf8").replaceAll("\r\n", "\n"))
				: current;
		if (!normalized?.equals(bytes)) stale.push(name);
	} else {
		await mkdir(dirname(destination), { recursive: true });
		await writeFile(destination, bytes);
	}
}
if (stale.length)
	throw new Error(`Brand assets are stale; run pnpm brand:generate:\n${stale.join("\n")}`);
console.log(`${check ? "Checked" : "Generated"} ${outputs.size} brand assets.`);
