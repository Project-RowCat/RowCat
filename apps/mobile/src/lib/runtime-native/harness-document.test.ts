import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { runInNewContext } from "node:vm";
import { describe, expect, it } from "vitest";
import {
	RUNTIME_HARNESS_CSP,
	RUNTIME_HARNESS_PRELUDE,
	runtimeHarnessDocument,
} from "./harness-document.ts";

/**
 * The harness document's Content-Security-Policy is the WebView realm's network fence if creator code
 * escapes QuickJS. Every token is pinned: a widened `connect-src` or a dropped `default-src 'none'`
 * compiles, generates and runs exactly as before, and the only symptom is a request that was meant
 * to be impossible.
 */

const ASSET = fileURLToPath(
	new URL(
		"../../../modules/rowcat-runtime-webview/assets/runtime/harness.html",
		import.meta.url,
	),
);

describe("harness CSP", () => {
	it("is exactly what the harness needs", () => {
		expect(RUNTIME_HARNESS_CSP).toBe(
			"default-src 'none'; script-src 'unsafe-inline' 'wasm-unsafe-eval'; connect-src 'self' file:; base-uri 'none'; form-action 'none'",
		);
	});

	it("opens no remote scheme and no general eval", () => {
		expect(RUNTIME_HARNESS_CSP).not.toMatch(/https?:|wss?:|data:|blob:|\*/);
		expect(RUNTIME_HARNESS_CSP).not.toMatch(/'unsafe-eval'/);
	});

	it("stands before the script in the document", () => {
		const html = runtimeHarnessDocument("post({type:'ready'})");
		const meta = html.indexOf('http-equiv="Content-Security-Policy"');
		expect(meta).toBeGreaterThan(-1);
		expect(meta).toBeLessThan(html.indexOf("<script>"));
		expect(html).toContain(`content="${RUNTIME_HARNESS_CSP}"`);
	});

	it("a bundle cannot close its own script tag", () => {
		const html = runtimeHarnessDocument('x = "</script><img src=x>"');
		/** Two closing tags: the prelude's and the bundle's own — none from inside the bundle. */
		expect(html.match(/<\/script>/g)).toHaveLength(2);
	});

	/** CSP does not reliably cover DNS prefetch; the document turns it off before anything runs. */
	it("turns DNS prefetch off before the scripts", () => {
		const html = runtimeHarnessDocument("post({type:'ready'})");
		const meta = html.indexOf(
			'<meta http-equiv="x-dns-prefetch-control" content="off">',
		);
		expect(meta).toBeGreaterThan(-1);
		expect(meta).toBeLessThan(html.indexOf("<script>"));
	});

	/**
	 * The committed asset is what the device loads. It is regenerated by
	 * `pnpm --filter @rowcat/mobile runtime-vm:harness` (and `--check` compares the bytes).
	 */
	it("the committed harness carries it", () => {
		const html = readFileSync(ASSET, "utf8");
		/** A boolean, not `toContain`: a failure would otherwise print the 3 MiB document. */
		const carries = html.includes(
			`<meta http-equiv="Content-Security-Policy" content="${RUNTIME_HARNESS_CSP}">`,
		);
		expect(carries, "regenerate with `runtime-vm:harness`").toBe(true);
	});
});

/**
 * No shipped CSP directive governs WebRTC (ICE/STUN/TURN), and both WebViews expose it without a
 * prompt. The document's scripts are run here in order, in a realm that has the constructors, and the
 * bundle must find none of them — while what the harness does need is untouched.
 */
describe("harness WebRTC removal", () => {
	const scriptsOf = (html: string): string[] =>
		[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(
			(match) => match[1] ?? "",
		);

	/**
	 * A realm shaped like a WebView's: constructors as configurable own properties of the global, one
	 * on the global's prototype (an engine that hangs interfaces there), and one that will not delete.
	 */
	function realm(): Record<string, unknown> {
		const context: Record<string, unknown> = { seen: null };
		runInNewContext(
			`
			["RTCPeerConnection", "webkitRTCPeerConnection", "RTCDataChannel", "RTCSessionDescription", "RTCEncodedVideoFrame", "fetch", "MessageChannel"].forEach(function (n) {
				Object.defineProperty(globalThis, n, { value: function () {}, writable: true, configurable: true });
			});
			Object.defineProperty(Object.getPrototypeOf(globalThis), "RTCIceCandidate", { value: function () {}, writable: true, configurable: true });
			Object.defineProperty(globalThis, "RTCRtpTransceiver", { value: function () {}, writable: true, configurable: false });
			`,
			context,
		);
		return context;
	}

	const probe =
		'seen = ["RTCPeerConnection","webkitRTCPeerConnection","RTCDataChannel","RTCSessionDescription","RTCIceCandidate","RTCRtpTransceiver","RTCEncodedVideoFrame"].filter(function (n) { return typeof globalThis[n] !== "undefined"; }).concat(typeof fetch, typeof WebAssembly, typeof MessageChannel);';

	it("the bundle runs in a realm with no WebRTC constructor", () => {
		const html = runtimeHarnessDocument(probe);
		const scripts = scriptsOf(html);
		expect(scripts.length).toBeGreaterThanOrEqual(2);
		const context = realm();
		for (const script of scripts) runInNewContext(script, context);
		expect(context.seen).toEqual(["function", "object", "function"]);
	});

	it("an escaped realm cannot put a shadowed one back", () => {
		const context = realm();
		for (const script of scriptsOf(runtimeHarnessDocument("")))
			runInNewContext(script, context);
		runInNewContext(
			"try { globalThis.RTCIceCandidate = function () {}; } catch (e) {} seen = typeof RTCIceCandidate;",
			context,
		);
		expect(context.seen).toBe("undefined");
	});

	/** The same asset check as the policy's: what the device loads must carry both. */
	it("the committed harness carries the prelude and the prefetch switch", () => {
		const html = readFileSync(ASSET, "utf8");
		const carries =
			html.includes(`<script>${RUNTIME_HARNESS_PRELUDE}</script>`) &&
			html.includes('<meta http-equiv="x-dns-prefetch-control" content="off">');
		expect(carries, "regenerate with `runtime-vm:harness`").toBe(true);
	});
});
