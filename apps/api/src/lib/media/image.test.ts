import { AVATAR_LIMITS, MEDIA_ERROR_CODE } from "@rowcat/contracts";
import sharp from "sharp";
import { describe, expect, it } from "vitest";
import { ApiError } from "../errors.ts";
import { normalizeImage } from "./image.ts";
import { AVATAR_POLICY, STORY_COVER_POLICY } from "./policy.ts";

/**
 * Tests the shared normalization boundary without a database. Unlike most api tests (real Postgres,
 * skipped when absent), `normalizeImage` has no ownership, transaction, storage or HTTP involved,
 * so this always runs, even on machines with no DB. The cover matrix already lives in
 * `lib/cover-image.test.ts` and still passes; this file covers only the axes the avatar policy
 * introduced and whether the two policies really diverge.
 *
 * Fixtures are generated by sharp at test time rather than committed as binaries, which nobody
 * could re-verify or read in review; the generating code is the fixture's spec.
 */

/** Deterministic pattern; `Math.random()` would make a failed CI run impossible to reproduce. */
const pattern = (width: number, height: number) => {
	const bytes = Buffer.alloc(width * height * 3);
	for (let y = 0; y < height; y += 1)
		for (let x = 0; x < width; x += 1) {
			const at = (y * width + x) * 3;
			bytes[at] = (x * 7 + y * 3) % 256;
			bytes[at + 1] = (x * 3 + y * 11) % 256;
			bytes[at + 2] = (x * 13 + y * 5) % 256;
		}
	return sharp(bytes, { raw: { width, height, channels: 3 } });
};

/** Checks a rejection whole: type, status and code must all match. */
const expectRejected = async (
	input: Buffer,
	policy: typeof AVATAR_POLICY,
	code: string,
) => {
	const thrown = await normalizeImage(input, policy).then(
		() => null,
		(error: unknown) => error,
	);
	// A non-`ApiError` would not go out as an `ApiErrorBody`; clients branch on `code`, so one plain
	// `Error` would defeat that branching.
	expect(thrown).toBeInstanceOf(ApiError);
	const error = thrown as ApiError;
	expect(error.status).toBe(400);
	expect(error.code).toBe(code);
};

describe("avatar — accepted formats", () => {
	/**
	 * If the input format leaked into the output, `media.mime` would be a transcribed claim; it would
	 * surface only as other formats' bytes served with an `image/webp` header, with no error.
	 */
	it("accepts JPEG · PNG · WebP and always returns WebP", async () => {
		const inputs = [
			await pattern(600, 600).jpeg().toBuffer(),
			await pattern(600, 600).png().toBuffer(),
			await pattern(600, 600).webp().toBuffer(),
		];
		for (const input of inputs) {
			const out = await normalizeImage(input, AVATAR_POLICY);
			expect(out.mime).toBe("image/webp");
			expect((await sharp(out.bytes).metadata()).format).toBe("webp");
		}
	});

	/**
	 * The most important test here. SVG is a document that can carry scripts, external entities and
	 * remote fonts, and libvips reads it with librsvg's XML parser; without the signature check first,
	 * that parser would run on our server. What this guards is not "rejected" but "never handed to the
	 * decoder", hence `unsupportedType` and not `invalidImage`.
	 */
	it("SVG is rejected by format before it reaches the decoder", async () => {
		const svg = Buffer.from(
			'<svg xmlns="http://www.w3.org/2000/svg" width="600" height="600"><rect width="600" height="600" fill="red"/></svg>',
		);
		await expectRejected(svg, AVATAR_POLICY, MEDIA_ERROR_CODE.unsupportedType);
	});

	/** Neither `Content-Type` nor extension is read: this is GIF bytes under a PNG name. */
	it("GIF is not accepted — whatever the name, the bytes answer", async () => {
		const gif = await pattern(600, 600).gif().toBuffer();
		await expectRejected(gif, AVATAR_POLICY, MEDIA_ERROR_CODE.unsupportedType);
	});

	it("an empty body and broken bytes split into different codes", async () => {
		await expectRejected(
			Buffer.alloc(0),
			AVATAR_POLICY,
			MEDIA_ERROR_CODE.empty,
		);
		// Valid PNG signature followed by garbage: the only path that passes stage 1 (signature) and dies
		// in stage 2 (real decode), proving both stages are live.
		const brokenPng = Buffer.concat([
			Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
			Buffer.from("what follows is not a PNG"),
		]);
		await expectRejected(
			brokenPng,
			AVATAR_POLICY,
			MEDIA_ERROR_CODE.invalidImage,
		);
	});
});

describe("avatar — size", () => {
	/**
	 * An axis covers lack. With cropping, "is anything left on the short side" matters; without a
	 * minimum, a 16x2000 strip would be cropped to 16x16 and stretched to 512px.
	 */
	it("rejects when the short side is below the minimum", async () => {
		const tiny = await pattern(
			AVATAR_LIMITS.minDimension - 1,
			AVATAR_LIMITS.minDimension - 1,
		)
			.png()
			.toBuffer();
		await expectRejected(
			tiny,
			AVATAR_POLICY,
			MEDIA_ERROR_CODE.invalidDimensions,
		);
	});

	/** This shape passes if measured by the long side; it pins `Math.min`, and `Math.max` breaks only this test. */
	it("rejects a strip image whose long side alone is large", async () => {
		const strip = await pattern(16, 2000).png().toBuffer();
		await expectRejected(
			strip,
			AVATAR_POLICY,
			MEDIA_ERROR_CODE.invalidDimensions,
		);
	});

	it("rejects a body over the limit", async () => {
		const huge = Buffer.concat([
			await pattern(600, 600).png().toBuffer(),
			Buffer.alloc(AVATAR_LIMITS.maxBytes),
		]);
		await expectRejected(huge, AVATAR_POLICY, MEDIA_ERROR_CODE.tooLarge);
	});

	/**
	 * Compression-bomb axis: a solid colour is tens of KB on disk but exceeds the pixel cap when
	 * unpacked, which file size cannot express. The code must be `invalidDimensions`, not
	 * `invalidImage`: the file is fine and the fix is shrinking it, so "check for corruption" would be
	 * a dead end.
	 */
	it("a pixel bomb is rejected by resolution, not as damage", async () => {
		const bomb = await sharp({
			create: {
				width: 6000,
				height: 5000,
				channels: 3,
				background: { r: 10, g: 120, b: 200 },
			},
		})
			.png()
			.toBuffer();
		expect(bomb.byteLength).toBeLessThan(AVATAR_LIMITS.maxBytes);
		expect(6000 * 5000).toBeGreaterThan(AVATAR_LIMITS.maxPixels);
		await expectRejected(
			bomb,
			AVATAR_POLICY,
			MEDIA_ERROR_CODE.invalidDimensions,
		);
	});
});

describe("avatar — normalization", () => {
	/** A square result regardless of ratio defines the avatar policy; screens need not use the contract's `width`/`height` for layout. */
	it("makes exactly a 512px square from any aspect ratio", async () => {
		for (const [w, h] of [
			[1200, 600],
			[600, 1200],
			[800, 800],
		]) {
			const out = await normalizeImage(
				await pattern(w, h).png().toBuffer(),
				AVATAR_POLICY,
			);
			expect([out.width, out.height]).toEqual([512, 512]);
		}
	});

	/**
	 * The minimum (64px) is below the output (512px), so enlargement must happen to guarantee a
	 * square. Enabling `withoutEnlargement` for `cover` would leave 128x128, which only this test
	 * reveals.
	 */
	it("fills a 512px square even from a source smaller than the output", async () => {
		const out = await normalizeImage(
			await pattern(128, 128).png().toBuffer(),
			AVATAR_POLICY,
		);
		expect([out.width, out.height]).toEqual([512, 512]);
	});

	/**
	 * Privacy axis: profile photos are often straight from a phone and carry GPS and device info;
	 * publishing that would disclose a location the user never agreed to share. ICC is the one
	 * exception because it is colour-rendering information, not personal data.
	 */
	it("drops EXIF entirely — the orientation goes into the pixels and no tag remains", async () => {
		// `orientation: 6` means "rotate 90 degrees"; with a square output the swap does not show in the
		// size, so the tag's absence is what is checked.
		const withExif = await pattern(800, 600)
			.withMetadata({ orientation: 6 })
			.jpeg()
			.toBuffer();
		expect((await sharp(withExif).metadata()).orientation).toBe(6);

		const out = await normalizeImage(withExif, AVATAR_POLICY);
		const meta = await sharp(out.bytes).metadata();
		expect(meta.orientation).toBeUndefined();
		expect(meta.exif).toBeUndefined();
	});

	/**
	 * ICC is kept because it is colour-rendering information; dropping it makes wide-gamut photos (P3,
	 * Adobe RGB) look oversaturated in browsers. It pairs with the EXIF test: both must pass for "keep
	 * only what is needed" to hold, otherwise removing `.keepIccProfile()` or switching to
	 * `.withMetadata()` would pass silently.
	 */
	it("keeps the ICC profile — what is dropped is personal data, not color", async () => {
		const wideGamut = await pattern(600, 600)
			.withIccProfile("p3")
			.png()
			.toBuffer();

		const out = await normalizeImage(wideGamut, AVATAR_POLICY);
		const meta = await sharp(out.bytes).metadata();
		expect(meta.icc).toBeDefined();
		/** Personal data is still gone. */
		expect(meta.exif).toBeUndefined();
	});
});

describe("policy separation", () => {
	/**
	 * Second most important test here. Sharing the pipeline must not share product rules, or covers
	 * would be cropped to 512x512. The same input runs through both policies and must differ, so a
	 * refactor merging the policies shows up immediately.
	 */
	it("the same input gives different results per policy", async () => {
		const input = await pattern(1200, 600).png().toBuffer();
		const avatar = await normalizeImage(input, AVATAR_POLICY);
		const cover = await normalizeImage(input, STORY_COVER_POLICY);

		/** Avatar crops to a square. */
		expect([avatar.width, avatar.height]).toEqual([512, 512]);
		/** Cover is not cropped; the 2:1 ratio stays. */
		expect(cover.width / cover.height).toBeCloseTo(2, 5);
		expect(cover.width).toBeLessThanOrEqual(1200);
	});

	/**
	 * Error vocabulary diverges too. If cover failure codes became `media_*`, every cover failure on
	 * deployed screens would fall into the `default` branch ("could not change the cover"); sharing
	 * infrastructure must not break a live contract.
	 */
	it("covers keep their own error vocabulary", async () => {
		const svg = Buffer.from('<svg xmlns="http://www.w3.org/2000/svg"/>');
		await expectRejected(
			svg,
			STORY_COVER_POLICY,
			"story_cover_unsupported_type",
		);
		await expectRejected(svg, AVATAR_POLICY, "media_unsupported_type");
	});
});
