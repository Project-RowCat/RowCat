/**
 * `GET · PUT · DELETE /v2/stories/:id/cover`: three verbs on one cover resource.
 *
 * This file guards five properties that break silently:
 *
 * 1. Cache identity comes from the bytes. `?v=` and the ETag are `story_cover.version` (a
 *    generated column), so a cover replaced twice in the same millisecond cannot serve different
 *    bytes at the same `immutable` address. Reverting to a time-based buster shows up as a one-year
 *    browser cache, not an error.
 * 2. A rejection never deletes an existing cover. Every rejection test fires at a story that
 *    already has a good cover and re-reads the stored bytes.
 * 3. The claimed format is not trusted. `Content-Type` is a browser guess or attacker input; the
 *    bytes decide, and the stored format is always one.
 * 4. Cover writes leave the story row untouched (counters, visibility, rating, `hidden`, and
 *    `updated_at`), or one image change would reorder `Published` or revive an operator-hidden story.
 * 5. Covers pass the same exposure boundary as the story; a cover usually reveals what the story
 *    is, so a loose boundary leaks private, hidden and adult content by id.
 *
 * It runs against real Postgres and the real Hono app: `version` is computed by the DB and the
 * ownership check is a `SELECT … FOR UPDATE` predicate, so mocking the service would leave the
 * subject outside the test. Image fixtures are generated by sharp at run time because a committed
 * binary cannot be verified in review.
 */

const EMAIL_PREFIX = "story-cover-test-";

interface Person {
	cookie: string;
	memberId: string;
}

/** A member; the final `/me` creates the member row (it is made on the first request, not at signup). */
const signUp = (name = "Cover test") =>
	createTestMember(EMAIL_PREFIX, { name });

/**
 * Operator account, made the way the seed script does it (writing the column directly); the product
 * API has no promotion path.
 */
async function signUpOperator(role: "staff" | "admin"): Promise<Person> {
	const account = await signUp("Cover operator");
	await db.update(member).set({ role }).where(eq(member.id, account.memberId));
	return account;
}

/** Legal eligibility to publish adult work; the display opt-in stays off. */
const grantAdultEligibility = (memberId: string) =>
	db
		.update(member)
		.set({ verified: true, adult: true, show_adult: false })
		.where(eq(member.id, memberId));

interface SeedStory {
	visibility?: "public" | "private" | "archived";
	adult?: boolean;
	hidden?: boolean;
}

async function seedStory(
	ownerId: string,
	options: SeedStory = {},
): Promise<string> {
	const id = newId();
	await db.insert(story).values({
		id,
		owner: ownerId,
		title: `Cover story ${id.slice(0, 6)}`,
		visibility: options.visibility ?? "public",
		adult: options.adult ?? false,
		hidden: options.hidden ?? false,
		origin_draft_id: `draft-${id}`,
		play_payload: { version: 1, storyId: id },
	});
	return id;
}

interface Rgb {
	r: number;
	g: number;
	b: number;
}

/** Two colors so that two same-size uploads produce different bytes. */
const RED: Rgb = { r: 214, g: 40, b: 40 };
const BLUE: Rgb = { r: 32, g: 64, b: 216 };

const canvas = (width: number, height: number, background: Rgb) =>
	sharp({ create: { width, height, channels: 3, background } });

const png = (width = 300, height = 400, color: Rgb = RED): Promise<Buffer> =>
	canvas(width, height, color).png().toBuffer();

const jpeg = (width = 300, height = 400, color: Rgb = RED): Promise<Buffer> =>
	canvas(width, height, color).jpeg().toBuffer();

const webp = (width = 300, height = 400, color: Rgb = RED): Promise<Buffer> =>
	canvas(width, height, color).webp().toBuffer();

const gif = (): Promise<Buffer> => canvas(40, 40, RED).gif().toBuffer();

const svg = (): Buffer =>
	Buffer.from(
		'<svg xmlns="http://www.w3.org/2000/svg" width="40" height="40">' +
			'<rect width="40" height="40" fill="#d62828"/></svg>',
	);

/** Only the PNG signature is real: passes stage 1 (magic bytes) and dies at stage 2 (decode). */
const pngSignatureThenGarbage = (): Buffer =>
	Buffer.concat([
		Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
		Buffer.alloc(256, 0x5a),
	]);

const headersOf = (
	cookie?: string | null,
	extra: Record<string, string> = {},
): Record<string, string> => ({
	Origin: WEB_ORIGIN,
	...(cookie ? { Cookie: cookie } : {}),
	...extra,
});

const coverPath = (storyId: string, query = ""): string =>
	`/v2/stories/${storyId}/cover${query}`;

const putCover = (
	storyId: string,
	cookie: string | null,
	body: Buffer,
	extra: Record<string, string> = {},
): Promise<Response> =>
	Promise.resolve(
		app.request(coverPath(storyId), {
			method: "PUT",
			headers: headersOf(cookie, extra),
			body,
		}),
	);

const deleteCover = (
	storyId: string,
	cookie: string | null,
): Promise<Response> =>
	Promise.resolve(
		app.request(coverPath(storyId), {
			method: "DELETE",
			headers: headersOf(cookie),
		}),
	);

const getCover = (
	storyId: string,
	cookie?: string | null,
	query = "",
	extra: Record<string, string> = {},
): Promise<Response> =>
	Promise.resolve(
		app.request(coverPath(storyId, query), {
			headers: headersOf(cookie, extra),
		}),
	);

const getDetail = (
	storyId: string,
	cookie?: string | null,
): Promise<Response> =>
	Promise.resolve(
		app.request(`/v2/stories/${storyId}`, { headers: headersOf(cookie) }),
	);

interface ErrorBody {
	code: string;
	message: string;
}

const codeOf = async (response: Response): Promise<string> =>
	((await response.json()) as ErrorBody).code;

/** The cover address the detail reports, which is what screens put in `<img src>`. */
const coverUrlOf = async (
	storyId: string,
	cookie?: string | null,
): Promise<string | null> => {
	const response = await getDetail(storyId, cookie);
	if (response.status !== 200)
		throw new Error(`the detail is ${response.status}`);
	return ((await response.json()) as { coverUrl: string | null }).coverUrl;
};

const coverRows = (storyId: string) =>
	db.select().from(story_cover).where(eq(story_cover.story_id, storyId));

const coverRow = async (storyId: string) => {
	const [row] = await coverRows(storyId);
	if (!row) throw new Error(`no cover row: ${storyId}`);
	return row;
};

const storyRow = async (storyId: string) => {
	const [row] = await db.select().from(story).where(eq(story.id, storyId));
	if (!row) throw new Error(`no story row: ${storyId}`);
	return row;
};

/**
 * Recomputes `story_cover.version` independently. Trusting the DB's value would not verify that the
 * version derives from the bytes: the test would pass even if the generated column switched to a
 * timestamp or sequence.
 */
const identityOf = (bytes: Buffer): string =>
	createHash("sha256").update(bytes).digest("hex").slice(0, 32);

/** Uploads a cover and returns its row: the "existing cover" for rejection tests. */
async function seedCoveredStory(
	owner: Person,
	options: SeedStory = {},
): Promise<{ storyId: string; bytes: Buffer; version: string }> {
	const storyId = await seedStory(owner.memberId, options);
	const response = await putCover(storyId, owner.cookie, await png(300, 400));
	expect(response.status).toBe(200);
	const row = await coverRow(storyId);
	return { storyId, bytes: row.bytes, version: row.version };
}

