describe.skipIf(!databaseReady)("cover storage — one cover per story", () => {
	/**
	 * If an upload turned into appending rows (a history table) this breaks first, silently: a story
	 * whose cover changed ten times would hold ten times the bytes.
	 */
	test("the first upload creates exactly one cover row", async () => {
		const storyId = await seedStory(OWNER.memberId);
		expect(await coverRows(storyId)).toHaveLength(0);

		const response = await putCover(storyId, OWNER.cookie, await png());
		expect(response.status).toBe(200);

		const rows = await coverRows(storyId);
		expect(rows).toHaveLength(1);
		expect(rows[0]?.story_id).toBe(storyId);
		expect(rows[0]?.bytes.length).toBeGreaterThan(0);
	});

	/**
	 * Split into `DELETE` then `INSERT`, a failure of the second statement would leave the cover gone
	 * entirely; the user's action was replace, not delete.
	 */
	test("replacing keeps one row and changes bytes and version together", async () => {
		const storyId = await seedStory(OWNER.memberId);
		await putCover(storyId, OWNER.cookie, await png(300, 400, RED));
		const before = await coverRow(storyId);

		await putCover(storyId, OWNER.cookie, await png(300, 400, BLUE));
		const after = await coverRow(storyId);

		expect(await coverRows(storyId)).toHaveLength(1);
		expect(after.bytes.equals(before.bytes)).toBe(false);
		expect(after.version).not.toBe(before.version);
		expect(after.mime).toBe("image/webp");
		expect(before.mime).toBe("image/webp");
	});

	/** Without idempotency a retry that only lost its response would look like an error. */
	test("deleting removes the row, and pressing twice still succeeds", async () => {
		const { storyId } = await seedCoveredStory(OWNER);

		expect((await deleteCover(storyId, OWNER.cookie)).status).toBe(200);
		expect(await coverRows(storyId)).toHaveLength(0);

		expect((await deleteCover(storyId, OWNER.cookie)).status).toBe(200);
		expect(await coverRows(storyId)).toHaveLength(0);
	});

	/**
	 * Without the FK's `onDelete: "cascade"`, ownerless cover bytes would remain forever, a leak
	 * visible only as storage growth.
	 */
	test("deleting the story removes its cover too", async () => {
		const { storyId } = await seedCoveredStory(OWNER);
		await db.delete(story).where(eq(story.id, storyId));
		expect(await coverRows(storyId)).toHaveLength(0);
	});

	/**
	 * If the stored format varied per input, the `mime` column would be a transcribed claim rather
	 * than a verified fact, and a JPEG labelled `image/png` could go out.
	 */
	test.each([
		["PNG", png],
		["JPEG", jpeg],
		["WebP", webp],
	] as const)("uploading %s still stores image/webp", async (_label, make) => {
		const storyId = await seedStory(OWNER.memberId);
		expect((await putCover(storyId, OWNER.cookie, await make())).status).toBe(
			200,
		);
		expect((await coverRow(storyId)).mime).toBe("image/webp");

		const read = await getCover(storyId, OWNER.cookie);
		expect(read.headers.get("Content-Type")).toBe("image/webp");
	});
});

describe.skipIf(!databaseReady)(
	"ownership — someone else's cover can't be touched",
	() => {
		/**
		 * If the ownership predicate left the SELECT (read, then check), someone else's cover could be
		 * overwritten in that window. So this checks the stored bytes are unchanged, not just the status.
		 */
		test("someone else uploading is a 404 and the original cover doesn't change by a byte", async () => {
			const { storyId, bytes, version } = await seedCoveredStory(OWNER);

			const response = await putCover(
				storyId,
				STRANGER.cookie,
				await png(300, 400, BLUE),
			);
			expect(response.status).toBe(404);
			expect(await codeOf(response)).toBe("not_found");

			const row = await coverRow(storyId);
			expect(row.bytes.equals(bytes)).toBe(true);
			expect(row.version).toBe(version);
		});

		test("someone else deleting is a 404 and the cover stays", async () => {
			const { storyId, version } = await seedCoveredStory(OWNER);

			const response = await deleteCover(storyId, STRANGER.cookie);
			expect(response.status).toBe(404);
			expect(await codeOf(response)).toBe("not_found");

			expect(await coverRows(storyId)).toHaveLength(1);
			expect((await coverRow(storyId)).version).toBe(version);
		});

		/**
		 * A guest is refused with 401, not 404, since logging in makes it possible and the screen has
		 * somewhere to go. Also checks the story row is untouched.
		 */
		test("a guest's PUT and DELETE are 401 and change nothing", async () => {
			const { storyId, bytes, version } = await seedCoveredStory(OWNER);
			const before = await storyRow(storyId);

			const put = await putCover(storyId, null, await png(300, 400, BLUE));
			expect(put.status).toBe(401);
			const remove = await deleteCover(storyId, null);
			expect(remove.status).toBe(401);

			const row = await coverRow(storyId);
			expect(row.bytes.equals(bytes)).toBe(true);
			expect(row.version).toBe(version);
			expect((await storyRow(storyId)).updated_at).toEqual(before.updated_at);
		});

		/**
		 * A missing story and someone else's must be the same 404; otherwise the cover path becomes a
		 * probe for "that id exists" and the detail's existence hiding collapses.
		 */
		test("PUT and DELETE on a missing story are the same 404 as on someone else's", async () => {
			const { storyId } = await seedCoveredStory(OWNER);
			const ghost = newId();

			const ghostPut = await putCover(ghost, OWNER.cookie, await png());
			const otherPut = await putCover(storyId, STRANGER.cookie, await png());
			expect(ghostPut.status).toBe(otherPut.status);
			expect(await codeOf(ghostPut)).toBe(await codeOf(otherPut));

			const ghostDelete = await deleteCover(ghost, OWNER.cookie);
			const otherDelete = await deleteCover(storyId, STRANGER.cookie);
			expect(ghostDelete.status).toBe(otherDelete.status);
			expect(await codeOf(ghostDelete)).toBe(await codeOf(otherDelete));
		});
	},
);

describe.skipIf(!databaseReady)(
	"validation — what is accepted and what isn't",
	() => {
		test.each([
			["JPEG", jpeg],
			["PNG", png],
			["WebP", webp],
		] as const)("%s passes", async (_label, make) => {
			const { storyId, version } = await seedCoveredStory(OWNER);
			const response = await putCover(
				storyId,
				OWNER.cookie,
				await make(200, 260),
			);
			expect(response.status).toBe(200);
			expect((await coverRow(storyId)).version).not.toBe(version);
		});

		/**
		 * A rejection must not delete an existing cover. This holds because normalization runs before the
		 * DB; reversed (delete first, validate later), one broken file would destroy a good cover
		 * irreversibly. Every rejection fires at a story with an existing cover and re-reads its bytes.
		 */
		const REJECTIONS: readonly {
			label: string;
			make: () => Promise<{ body: Buffer; extra?: Record<string, string> }>;
			status: number;
			code: string;
		}[] = [
			{
				label: "a file with junk after a PNG signature",
				make: async () => ({ body: pngSignatureThenGarbage() }),
				status: 400,
				code: STORY_COVER_ERROR_CODE.invalidImage,
			},
			{
				label: "a JPEG cut off in the middle",
				make: async () => {
					const good = await jpeg(400, 300);
					return { body: good.subarray(0, Math.floor(good.length / 3)) };
				},
				status: 400,
				code: STORY_COVER_ERROR_CODE.invalidImage,
			},
			{
				label: "an SVG document",
				make: async () => ({ body: svg() }),
				status: 400,
				code: STORY_COVER_ERROR_CODE.unsupportedType,
			},

			{
				label: "an empty body",
				make: async () => ({ body: Buffer.alloc(0) }),
				status: 400,
				code: STORY_COVER_ERROR_CODE.empty,
			},
			{
				/**
				 * Pre-read cap: stops any format. `bodyLimit` stands at the larger per-format cap (GIF, 20MiB)
				 * because the format is unknown before reading; the narrower cap is enforced after the signature
				 * check (see the case below).
				 *
				 * `Content-Length` is sent explicitly: it is what `bodyLimit` checks first, so the "reject
				 * before reading the body" path actually runs. Without it the request takes the stream-counting
				 * branch and the same code comes from a different place.
				 */
				label: "a body over the pre-read limit (20MiB)",
				make: async () => {
					const body = Buffer.alloc(
						STORY_COVER_LIMITS.maxAnimatedBytes + 1,
						0x00,
					);
					return { body, extra: { "Content-Length": String(body.length) } };
				},
				status: 413,
				code: STORY_COVER_ERROR_CODE.tooLarge,
			},
			{
				/**
				 * Post-read cap: the narrower still-image cap (5MiB) applies here. The status differs from above
				 * (413 vs 400) because rejection happens elsewhere, but the code is the same (`tooLarge`) since
				 * the user's remedy is the same; screens branch on code, not status.
				 */
				label: "a PNG over the still-image limit (5MiB)",
				make: async () => {
					const body = Buffer.concat([
						Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
						Buffer.alloc(STORY_COVER_LIMITS.maxBytes + 1, 0x00),
					]);
					return { body, extra: { "Content-Length": String(body.length) } };
				},
				status: 400,
				code: STORY_COVER_ERROR_CODE.tooLarge,
			},
			{
				/**
				 * The per-side axis. 10,001 × 2 is only 20k pixels, so it touches the resolution axis alone;
				 * testing both axes with one fixture would hide which one rejected.
				 */
				label: "an image with a side over the limit",
				make: async () => ({
					body: await png(STORY_COVER_LIMITS.maxDimension + 1, 2),
				}),
				status: 400,
				code: STORY_COVER_ERROR_CODE.dimensionsTooLarge,
			},
			{
				/**
				 * The total-pixel axis (6,000 × 5,000 = 30M > 24M). Both sides are within `maxDimension`, so
				 * only this axis rejects.
				 *
				 * This is where the code easily flips to `invalidImage`: applying `limitInputPixels` to the
				 * header-reading probe makes libvips throw there, folding into `invalidImage`, so someone with a
				 * perfectly good photo is told to check for corruption and never told to shrink it. Hence the
				 * pinned code.
				 */
				label: "an image over the total pixel limit",
				make: async () => ({ body: await jpeg(6000, 5000) }),
				status: 400,
				code: STORY_COVER_ERROR_CODE.dimensionsTooLarge,
			},
		];

		test.each(
			REJECTIONS,
		)("$label is refused and the original cover stays", async ({
			make,
			status,
			code,
		}) => {
			const { storyId, bytes, version } = await seedCoveredStory(OWNER);
			const { body, extra } = await make();

			const response = await putCover(storyId, OWNER.cookie, body, extra);
			expect(response.status).toBe(status);
			expect(await codeOf(response)).toBe(code);

			const row = await coverRow(storyId);
			expect(row.bytes.equals(bytes)).toBe(true);
			expect(row.version).toBe(version);
		}, 30_000);

		/**
		 * GIF is accepted, for its motion (`lib/media/policy.ts`). It used to be in the rejection table
		 * above; the rule change is inverted into an accepting case so this file still says how the
		 * endpoint treats GIF. Whether frames survive needs hand-built fixtures and is covered by
		 * `lib/media/animated-image.test.ts`; here we check the boundary is open and the stored format is
		 * still one.
		 */
		test("a GIF passes and is stored as webp", async () => {
			const storyId = await seedStory(OWNER.memberId);

			const response = await putCover(storyId, OWNER.cookie, await gif());
			expect(response.status).toBe(200);

			const row = await coverRow(storyId);
			expect(row.mime).toBe("image/webp");
		});
	},
);

