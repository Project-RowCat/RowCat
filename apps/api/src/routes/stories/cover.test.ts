describe.skipIf(!databaseReady)(
	"concurrency — bytes and version always say the same thing",
	() => {
		/**
		 * Two devices upload different covers at the same moment. Which wins does not matter (both are
		 * valid); the invariants are one row, and that row's `version` matches its own bytes.
		 *
		 * An application-computed version could break here: one transaction's bytes could carry another's
		 * version, producing an immutable cache that is never refreshed.
		 */
		test("two different uploads arriving at once leave one row with a matching version", async () => {
			const storyId = await seedStory(OWNER.memberId);
			const [red, blue] = await Promise.all([
				png(300, 400, RED),
				png(300, 400, BLUE),
			]);

			const results = await Promise.all([
				putCover(storyId, OWNER.cookie, red),
				putCover(storyId, OWNER.cookie, blue),
			]);
			// One may lose, but the loser must not die with a 500.
			for (const response of results)
				expect([200, 409, 404]).toContain(response.status);
			expect(results.some((response) => response.status === 200)).toBe(true);

			const rows = await coverRows(storyId);
			expect(rows).toHaveLength(1);
			const row = rows[0];
			if (!row) throw new Error("no cover row");
			expect(row.version).toBe(identityOf(row.bytes));
			expect([identityOf(red), identityOf(blue)]).not.toContain(row.version);

			// The last committed state is the address the screen receives.
			expect(await coverUrlOf(storyId, OWNER.cookie)).toContain(row.version);
		});

		/**
		 * Overlapping replace and delete leave one of two states (present or absent). What must not exist
		 * is a third: new bytes with the old version.
		 */
		test("even when upload and delete overlap, 0 or 1 rows remain and the version never disagrees", async () => {
			const { storyId } = await seedCoveredStory(OWNER);

			const [put, remove] = await Promise.all([
				putCover(storyId, OWNER.cookie, await png(300, 400, BLUE)),
				deleteCover(storyId, OWNER.cookie),
			]);
			expect([200, 404]).toContain(put.status);
			expect([200, 404]).toContain(remove.status);

			const rows = await coverRows(storyId);
			expect(rows.length).toBeLessThanOrEqual(1);
			const row = rows[0];
			if (row) expect(row.version).toBe(identityOf(row.bytes));
		});
	},
);
