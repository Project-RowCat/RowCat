describe.skipIf(!databaseReady)("moderation doesn't touch covers", () => {
	/** Files one report and returns the case id; enforcement comes only from a case. */
	async function openCase(storyId: string): Promise<string> {
		const reporter = await signUp("Reporter");
		const created = await app.request("/v2/reports", {
			method: "POST",
			headers: headersOf(reporter.cookie, {
				"Content-Type": "application/json",
			}),
			body: JSON.stringify({
				target: { type: "story", storyId },
				reason: "spam",
			}),
		});
		const { reportId } = (await created.json()) as { reportId: string };
		const detail = await app.request(`/v2/moderation/reports/${reportId}`, {
			headers: headersOf(OPERATOR.cookie),
		});
		const { caseId } = (await detail.json()) as { caseId: string };
		CREATED_CASES.push(caseId);
		return caseId;
	}

	const act = (caseId: string, kind: string, reason: string) =>
		app.request("/v2/moderation/actions", {
			method: "POST",
			headers: headersOf(OPERATOR.cookie, {
				"Content-Type": "application/json",
			}),
			body: JSON.stringify({ caseId, kind, reason }),
		});

	/**
	 * If hide/unhide rewrote the cover, every viewer's cache would be invalidated for no reason, and
	 * bumping `updated_at` would lift an untouched story to the top of `Published`, which the creator
	 * reads as an edit they never made.
	 */
	test("hiding and unhiding keep the cover bytes, version and the story's updated time", async () => {
		const { storyId, bytes, version } = await seedCoveredStory(OWNER, {
			visibility: "public",
		});
		const before = await storyRow(storyId);
		const caseId = await openCase(storyId);

		expect((await act(caseId, "hide_story", "Under review")).status).toBe(201);
		expect((await getCover(storyId, null)).status).toBe(404);

		expect((await act(caseId, "unhide_story", "false positive")).status).toBe(
			201,
		);

		const row = await coverRow(storyId);
		expect(row.bytes.equals(bytes)).toBe(true);
		expect(row.version).toBe(version);
		expect((await storyRow(storyId)).updated_at).toEqual(before.updated_at);
		expect((await getCover(storyId, null)).status).toBe(200);
	});

	/**
	 * The reverse direction. If a cover write issued even one UPDATE against the `story` row,
	 * replacing the image would lift an operator's hide, an enforcement bypass inside a product
	 * feature that is recorded nowhere.
	 */
	test("uploading a cover to a hidden story keeps hidden true", async () => {
		const { storyId } = await seedCoveredStory(OWNER, { visibility: "public" });
		const caseId = await openCase(storyId);
		await act(caseId, "hide_story", "Under review");

		const response = await putCover(
			storyId,
			OWNER.cookie,
			await png(300, 400, BLUE),
		);
		expect(response.status).toBe(200);

		const row = await storyRow(storyId);
		expect(row.hidden).toBe(true);
		expect(row.visibility).toBe("public");
		// While hidden, the new cover is not served either.
		expect((await getCover(storyId, null)).status).toBe(404);
	});
});

