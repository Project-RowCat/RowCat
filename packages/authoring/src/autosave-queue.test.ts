import { describe, expect, it } from "vitest";
import {
	commitQueue,
	createAutosaveQueue,
	type PendingEntry,
} from "./autosave-queue.ts";
import type { AuthoringStore } from "./store.ts";

/**
 * Autosave queue: does what the user typed survive?
 *
 * Everything that breaks here breaks silently. The screen still shows the value just typed, and the
 * loss goes unnoticed until the tab is closed and reopened. So ordinary write failures are
 * triggered for real: quota exceeded, and a transaction aborted by a schema upgrade in another tab.
 *
 * The store needs only identity. This layer only knows whether two stores are the same. The real
 * writes are done by the injected `commit`. The real IndexedDB rules are tested in
 * `local-authoring/store.test.ts`.
 */

const storeOf = (label: string): AuthoringStore =>
	({ label }) as unknown as AuthoringStore;

const alice = storeOf("alice");
const bob = storeOf("bob");

const entry = (
	id: string,
	patch: Record<string, unknown>,
	store: AuthoringStore = alice,
): PendingEntry => ({ kind: "draft", id, patch, store });

/** A write that always succeeds. It only records what was written, and in what order. */
function recorder() {
	const written: PendingEntry[] = [];
	return {
		written,
		commit: async (item: PendingEntry) => {
			written.push(item);
		},
	};
}

describe("merging", () => {
	it("changes to the same record fold into one write", () => {
		const queue = createAutosaveQueue();
		queue.push(entry("d1", { title: "Night" }));
		queue.push(entry("d1", { prompt: "library" }));
		queue.push(entry("d1", { title: "The Night Library" }));

		const drained = queue.drain();
		expect(drained).toHaveLength(1);
		// The later value wins, and fields not touched survive.
		expect(drained[0]?.patch).toEqual({
			title: "The Night Library",
			prompt: "library",
		});
	});

	it("changes to different records stay separate", () => {
		const queue = createAutosaveQueue();
		queue.push(entry("d1", { title: "a" }));
		queue.push({ ...entry("l1", { content: "setting" }), kind: "lore" });

		expect(queue.size).toBe(2);
	});

	it("does not hand earlier changes to a new store", () => {
		/**
		 * The case of signing in to a different account after logout. Local draft ids are generated by
		 * the device and stay valid, and merging on the same key alone would graft the previous session's
		 * sentence onto the current session's value.
		 */
		const queue = createAutosaveQueue();
		queue.push(entry("d1", { title: "Alice's manuscript" }));
		queue.push(entry("d1", { prompt: "Bob's manuscript" }, bob));

		const drained = queue.drain();
		expect(drained).toHaveLength(1);
		expect(drained[0]?.patch).toEqual({ prompt: "Bob's manuscript" });
		expect(drained[0]?.store).toBe(bob);
	});
});

describe("one write pass", () => {
	it("writes pending changes in scheduling order and empties the queue", async () => {
		const queue = createAutosaveQueue();
		queue.push(entry("d1", { title: "a" }));
		queue.push(entry("d2", { title: "b" }));
		const { written, commit } = recorder();

		const result = await commitQueue({ queue, ownsStore: () => true, commit });

		expect(result.status).toBe("saved");
		expect(written.map((item) => item.id)).toEqual(["d1", "d2"]);
		expect(queue.size).toBe(0);
	});

	it("a change arriving during the write is not 'saved'", async () => {
		const queue = createAutosaveQueue();
		queue.push(entry("d1", { title: "a" }));

		const result = await commitQueue({
			queue,
			ownsStore: () => true,
			commit: async () => {
				// The user typed one more character while the write was in progress.
				queue.push(entry("d1", { title: "ab" }));
			},
		});

		expect(result.status).toBe("pending");
		expect(queue.size).toBe(1);
	});

	it("changes whose ownership moved are dropped rather than flushed", async () => {
		/**
		 * If left in place, the next round makes the same judgement again. Meanwhile, if the original
		 * account comes back, a value from minutes ago would overwrite the current one. That edit belongs
		 * to a session that already ended.
		 */
		const queue = createAutosaveQueue();
		queue.push(entry("d1", { title: "previous session" }, bob));
		const { written, commit } = recorder();

		const result = await commitQueue({
			queue,
			ownsStore: (store) => store === alice,
			commit,
		});

		expect(result.status).toBe("empty");
		expect(written).toHaveLength(0);
		expect(queue.size).toBe(0);
	});
});

describe("write failures", () => {
	/** A write that fails on the second item. The first one is already on disk. */
	function failingAt(failId: string) {
		const written: string[] = [];
		return {
			written,
			commit: async (item: PendingEntry) => {
				if (item.id === failId) throw new Error("QuotaExceededError");
				written.push(item.id);
			},
		};
	}

	it("failed changes return to the queue", async () => {
		/**
		 * This test is the reason for this file. Before, the queue was drained just before the write. On
		 * failure, the sentence the user typed stayed only on screen, and one reload made it disappear.
		 */
		const queue = createAutosaveQueue();
		queue.push(entry("d1", { title: "a" }));
		queue.push(entry("d2", { title: "b" }));
		const { written, commit } = failingAt("d2");

		const result = await commitQueue({ queue, ownsStore: () => true, commit });

		expect(result.status).toBe("failed");
		expect(written).toEqual(["d1"]);
		// Already-written items are not rolled back. Rolling back would make the next round rewrite the
		// old value.
		const remaining = queue.drain();
		expect(remaining.map((item) => item.id)).toEqual(["d2"]);
		expect(remaining[0]?.patch).toEqual({ title: "b" });
	});

	it("retrying saves the change that failed", async () => {
		const queue = createAutosaveQueue();
		queue.push(entry("d1", { prompt: "A library where books talk" }));

		const first = await commitQueue({
			queue,
			ownsStore: () => true,
			commit: failingAt("d1").commit,
		});
		expect(first.status).toBe("failed");

		const { written, commit } = recorder();
		const second = await commitQueue({ queue, ownsStore: () => true, commit });

		expect(second.status).toBe("saved");
		expect(written[0]?.patch).toEqual({
			prompt: "A library where books talk",
		});
	});

	it("a returned value does not overwrite values that arrived meanwhile", async () => {
		const queue = createAutosaveQueue();
		queue.push(entry("d1", { title: "a", prompt: "first" }));

		const result = await commitQueue({
			queue,
			ownsStore: () => true,
			commit: async () => {
				// While the write was failing, the user fixed the title again.
				queue.push(entry("d1", { title: "b" }));
				throw new Error("AbortError");
			},
		});
		expect(result.status).toBe("failed");

		const drained = queue.drain();
		expect(drained).toHaveLength(1);
		// The new title wins, and the other fields of the failed write survive.
		expect(drained[0]?.patch).toEqual({ title: "b", prompt: "first" });
	});

	/**
	 * Discard actually discards.
	 *
	 * A person who chooses to leave after a failed save makes that choice here (`discard` in
	 * `use-draft-autosave.ts`). If the queue were not emptied, the final flush on unmount would try to
	 * write it again. If that write succeeded, the edit the user chose to discard would come back, an
	 * undo the user did not perform.
	 */
	it("after dropping, the next pass writes nothing", async () => {
		const queue = createAutosaveQueue();
		queue.push(entry("d1", { title: "title to drop" }));

		const failed = await commitQueue({
			queue,
			ownsStore: () => true,
			commit: failingAt("d1").commit,
		});
		expect(failed.status).toBe("failed");
		expect(queue.size).toBe(1);

		// Stands in for `discard()`: empties the queue without writing.
		queue.drain();
		expect(queue.size).toBe(0);

		const { written, commit } = recorder();
		const after = await commitQueue({ queue, ownsStore: () => true, commit });

		expect(after.status).toBe("empty");
		expect(written).toEqual([]);
	});

	it("does not mix in the previous session's values when the account changed during the return", async () => {
		const queue = createAutosaveQueue();
		queue.push(entry("d1", { title: "Alice's manuscript" }));

		await commitQueue({
			queue,
			ownsStore: () => true,
			commit: async () => {
				queue.push(entry("d1", { title: "Bob's manuscript" }, bob));
				throw new Error("AbortError");
			},
		});

		const drained = queue.drain();
		expect(drained).toHaveLength(1);
		expect(drained[0]?.store).toBe(bob);
		expect(drained[0]?.patch).toEqual({ title: "Bob's manuscript" });
	});
});
