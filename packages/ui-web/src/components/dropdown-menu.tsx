/*
  The check inside a menu row used to blink between rows: picking `Popular` in the gallery's
  sort menu keeps the menu open (the period comes next), and radio items stay open by
  default, so the mark visibly teleported while the user was looking at it.

  It now reads the same two lifetime attributes the checkbox's mark reads — Base UI's menu
  indicators mount and unmount through the same `useTransitionStatus`, and wait on the
  indicator's own `getAnimations()` before unmounting, which is why opacity must move in
  both directions. A row that is already checked when the menu opens does not animate
  (it mounts without `starting`). Reduced motion drops the scale and keeps the fade.
*/
const menuIndicatorClassName = cn(
  "flex items-center justify-center",
  "transition-[opacity,scale] motion-reduce:transition-opacity",
  "data-starting-style:scale-80 data-starting-style:opacity-0",
  "data-ending-style:scale-85 data-ending-style:opacity-0"
)

