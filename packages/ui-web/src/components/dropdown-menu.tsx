function DropdownMenuContent({
  align = "start",
  alignOffset = 0,
  side = "bottom",
  sideOffset = 4,
  className,
  ...props
}: MenuPrimitive.Popup.Props &
  Pick<
    MenuPrimitive.Positioner.Props,
    "align" | "alignOffset" | "side" | "sideOffset"
  >) {
  return (
    <MenuPrimitive.Portal>
      <MenuPrimitive.Positioner
        className="isolate z-50 outline-none"
        align={align}
        alignOffset={alignOffset}
        side={side}
        sideOffset={sideOffset}
      >
        <MenuPrimitive.Popup
          data-slot="dropdown-menu-content"
          className={cn("z-50 max-h-(--available-height) w-(--anchor-width) min-w-32 origin-(--transform-origin) overflow-x-hidden overflow-y-auto rounded-md bg-popover p-1 text-popover-foreground shadow-md ring-1 ring-foreground/10 outline-none data-closed:overflow-hidden", className )}
          {...props}
          /*
            Submenus render through this component too (`DropdownMenuSubContent`),
            so the direction table is written once. The old class strings had it
            twice, and the submenu copy was missing the two `inline-*` sides.

            `data-closed:overflow-hidden` stays. It is not motion — it keeps the
            scrollbar from flashing while the popup shrinks, and Base UI still sets
            the attribute it hangs off.
          */
          render={(htmlProps, state) => (
            <m.div
              {...(htmlProps as HTMLMotionProps<"div">)}
              {...popupMotion(state.side, state.open)}
            />
          )}
        />
      </MenuPrimitive.Positioner>
    </MenuPrimitive.Portal>
  )
}

